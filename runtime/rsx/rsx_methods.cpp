const char* method_name(uint32_t reg, uint32_t& index) {
    for (const Range& r : kRanges) {
        const uint32_t i = (reg - r.first) / 4;
        if (reg >= r.first && i < r.count) {
            index = i / r.stride;
            return r.name;
        }
    }
    index = 0;
    return nullptr;
}

