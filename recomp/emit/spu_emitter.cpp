bool emit_spu_blocks(const std::vector<SpuCachedBlock>& in_blocks, const std::string& out_dir, SpuEmitStats& stats,
                     std::string& error) {
    namespace fs = std::filesystem;
    std::error_code ec;
    fs::create_directories(out_dir, ec);
    if (ec) {
        error = "não foi possível criar " + out_dir;
        return false;
    }
    // Same order on every run: by address, then by code.
    std::vector<const SpuCachedBlock*> blocks;
    for (const SpuCachedBlock& b : in_blocks) blocks.push_back(&b);
    std::sort(blocks.begin(), blocks.end(), [](const SpuCachedBlock* a, const SpuCachedBlock* b) {
        return a->pc != b->pc ? a->pc < b->pc : a->code < b->code;
    });
    blocks.erase(std::unique(blocks.begin(), blocks.end(),
                             [](const SpuCachedBlock* a, const SpuCachedBlock* b) {
                                 return a->pc == b->pc && a->code == b->code;
                             }),
                 blocks.end());

    std::vector<std::string> sources;
    size_t files = 0;
    for (size_t first = 0; first < blocks.size(); first += kBlocksPerFile, ++files) {
        char name[32];
        std::snprintf(name, sizeof(name), "spu_%04zu.cpp", files);
        std::ofstream o(fs::path(out_dir) / name);
        o << "// Generated by sly4_recomp spu-emit from SPU code of the user's game. Do not edit; not for "
             "distribution.\n#include \"cpu/spu_blocks.h\"\n\nnamespace sly4::spugen {\n\nusing namespace sly4;\n"
             "using namespace sly4::spusem;\n\nnamespace {\n\n";
        const size_t last = std::min(blocks.size(), first + kBlocksPerFile);
        for (size_t i = first; i < last; ++i) write_block(o, *blocks[i], i, stats);
        o << "const SpuBlockEntry kBlocks[] = {\n";
        for (size_t i = first; i < last; ++i) {
            const std::string bn = block_name(blocks[i]->pc, i);
            char line[128];
            std::snprintf(line, sizeof(line), "    {0x%05Xu, %zu, c%s, &%s},\n", blocks[i]->pc, blocks[i]->code.size(),
                          bn.substr(1).c_str(), bn.c_str());
            o << line;
        }
        o << "};\n\n}  // namespace\n\nvoid register_spu_blocks_" << files << "() { spu_register_blocks(kBlocks, "
          << last - first << "); }\n\n}  // namespace sly4::spugen\n";
        sources.push_back(name);
    }
    {
        std::ofstream t(fs::path(out_dir) / "table.cpp");
        t << "// Generated by sly4_recomp spu-emit. Do not edit.\nnamespace sly4::spugen {\n\n";
        for (size_t i = 0; i < files; ++i) t << "void register_spu_blocks_" << i << "();\n";
        t << "\n}  // namespace sly4::spugen\n\nnamespace sly4::gen {\n\nvoid register_spu_blocks() {\n";
        for (size_t i = 0; i < files; ++i) t << "    spugen::register_spu_blocks_" << i << "();\n";
        t << "}\n\n}  // namespace sly4::gen\n";
        sources.push_back("table.cpp");
    }
    {
        std::ofstream s(fs::path(out_dir) / "sources.cmake");
        s << "# Generated by sly4_recomp spu-emit.\nset(SLY4_GEN_SOURCES\n";
        for (const auto& n : sources) s << "    ${CMAKE_CURRENT_LIST_DIR}/" << n << "\n";
        s << ")\n";
    }
    stats.blocks = blocks.size();
    stats.files = sources.size();
    return true;
}

void spu_static_blocks(const uint8_t* ls, const std::vector<std::pair<uint32_t, uint32_t>>& code_ranges,
                       uint32_t entry, std::vector<SpuCachedBlock>& out) {
    auto in_code = [&](uint32_t a) {
        for (const auto& [lo, hi] : code_ranges)
            if (a >= lo && a < hi) return true;
        return false;
    };
    std::set<uint32_t> entries;
    if (in_code(entry)) entries.insert(entry);
    for (const auto& [lo, hi] : code_ranges) {
        for (uint32_t ip = lo; ip + 4 <= hi; ip += 4) {
            const Insn in = spu::decode(load_be<uint32_t>(ls + ip));
            uint32_t target;
            if (spu::direct_target(in, ip, target) && in_code(target)) entries.insert(target);
            const bool call = in.op == Op::brsl || in.op == Op::brasl || in.op == Op::bisl;
            if ((call || spu::ends_block(in.op)) && in.op != Op::invalid && in_code(ip + 4) &&
                spu::decode(load_be<uint32_t>(ls + ip + 4)).op != Op::invalid)
                entries.insert(ip + 4);
        }
    }
    for (uint32_t pc : entries) {
        SpuCachedBlock b;
        b.pc = pc;
        b.code.assign(ls + pc, ls + pc + spu_block_size(ls, pc));
        out.push_back(std::move(b));
    }
}

