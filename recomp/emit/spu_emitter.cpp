constexpr size_t kBlocksPerFile = 400;

std::string block_name(uint32_t pc, size_t index) {
    char b[32];
    std::snprintf(b, sizeof(b), "b_%05X_%zu", pc, index);
    return b;
}

// Instructions that read c.pc besides the ones that may leave the block.
bool reads_pc(Op op) { return op == Op::lqr || op == Op::stqr; }

void write_block(std::ostream& o, const SpuCachedBlock& b, size_t index, SpuEmitStats& stats) {
    const std::string name = block_name(b.pc, index);
    const uint32_t words = uint32_t(b.code.size() / 4);
    o << "alignas(16) const uint8_t c" << name.substr(1) << "[] = {";
    for (size_t i = 0; i < b.code.size(); ++i) {
        if (i % 16 == 0) o << "\n    ";
        char h[8];
        std::snprintf(h, sizeof(h), "0x%02X,", b.code[i]);
        o << h;
    }
    o << "\n};\n";
    o << "SpuStep " << name << "(SPUContext& c, uint64_t& n) {\n    SpuStep st;\n";
    bool ended = false;
    for (uint32_t i = 0; i < words; ++i) {
        const uint32_t ip = b.pc + 4 * i;
        const Insn in = spu::decode(load_be<uint32_t>(b.code.data() + 4 * i));
        char line[160];
        std::snprintf(line, sizeof(line), "    // %05X  %s\n", ip, spu::disasm(in, ip).c_str());
        o << line;
        ++stats.instructions;
        if (in.op == Op::invalid) {
            std::snprintf(line, sizeof(line), "    c.pc = 0x%05Xu;\n    return spu_block_leave(SpuStep::Invalid, n, %u);\n",
                          ip, i);
            o << line;
            ended = true;
            break;
        }
        char call[96];
        std::snprintf(call, sizeof(call), "op<Op::%s>(c, Insn{Op::%s, 0x%08Xu})", spu::enum_name(in.op),
                      spu::enum_name(in.op), in.w);
        if (spu::ends_block(in.op)) {
            std::snprintf(line, sizeof(line), "    c.pc = 0x%05Xu;\n    return spu_block_leave(%s, n, %u);\n", ip,
                          call, i);
            o << line;
            ended = true;
            break;
        }
        if (spu::may_leave(in.op)) {
            std::snprintf(line, sizeof(line),
                          "    c.pc = 0x%05Xu;\n    if ((st = %s) != SpuStep::Ok) return spu_block_leave(st, n, %u);\n", ip,
                          call, i);
        } else if (reads_pc(in.op)) {
            std::snprintf(line, sizeof(line), "    c.pc = 0x%05Xu;\n    %s;\n", ip, call);
        } else {
            std::snprintf(line, sizeof(line), "    %s;\n", call);
        }
        o << line;
    }
    if (!ended) {  // the block was cut (size limit or end of local store): go on from there
        char line[128];
        std::snprintf(line, sizeof(line), "    c.pc = 0x%05Xu;\n    n += %u;\n    return SpuStep::Branch;\n",
                      (b.pc + 4 * words) & (kSpuLsSize - 1), words);
        o << line;
    }
    o << "    (void)st;\n}\n\n";
}

